/**
 * Universal Direct Print Portal & Executor
 * Resolves all iframe sandbox blocks, mobile popup blocks, and window.open restrictions
 * by directly leveraging standard CSS @media print, in-DOM print portal, and in-app print preview.
 */

export interface PrintPreviewEventDetail {
  html: string;
  title?: string;
  timestamp: number;
}

const PRINT_PORTAL_ID = 'falcon-print-portal';
const PRINT_EVENT_NAME = 'falcon:open-print-preview';

/**
 * Ensures the print portal container exists in DOM
 */
function getOrCreatePrintPortal(): HTMLElement {
  let portal = document.getElementById(PRINT_PORTAL_ID);
  if (!portal) {
    portal = document.createElement('div');
    portal.id = PRINT_PORTAL_ID;
    document.body.appendChild(portal);
  }
  return portal;
}

/**
 * Triggers a direct browser print while also opening the in-app Print & Thermal Preview Modal
 * so the user always has a 100% reliable, visible way to print or save the document even
 * if the browser sandbox blocks window.print() or popups.
 */
export function triggerDirectPrint(options: {
  html: string;
  title?: string;
  silent?: boolean;
}): void {
  if (typeof window === 'undefined') return;

  const { html, title = 'Document Print' } = options;

  // 1. Populate the in-DOM print portal
  const portal = getOrCreatePrintPortal();
  portal.innerHTML = html;

  // 2. Dispatch in-app Print Preview Event so the interactive modal displays on-screen
  try {
    const detail: PrintPreviewEventDetail = {
      html,
      title,
      timestamp: Date.now()
    };
    window.dispatchEvent(new CustomEvent(PRINT_EVENT_NAME, { detail }));
  } catch (err) {
    console.debug('Print preview event notice:', err);
  }

  // 3. Mark body as printing-active for @media print CSS isolation
  document.body.classList.add('printing-active');

  const cleanup = () => {
    document.body.classList.remove('printing-active');
  };

  window.addEventListener('afterprint', cleanup, { once: true });
  setTimeout(cleanup, 20000);

  // 4. Invoke system print dialog safely
  try {
    window.print();
  } catch (printErr) {
    console.debug('Browser window.print() notice (preview modal active):', printErr);
  }
}

/**
 * Prints an image document (e.g. Gate Pass dispatch receipt or blueprint JPG)
 */
export function triggerImagePrint(options: {
  imageUrl: string;
  title?: string;
  subtitle?: string;
}): void {
  const { imageUrl, title = 'Gate Pass Document', subtitle = 'Falcon Rod Maker · Official Gate Record' } = options;

  const html = `
    <div style="text-align: center; padding: 20px; font-family: monospace; background: #fff; color: #000;">
      <h2 style="margin: 0 0 4px 0; font-size: 16px; text-transform: uppercase;">${title}</h2>
      <p style="margin: 0 0 16px 0; font-size: 12px; color: #555;">${subtitle}</p>
      <div style="display: flex; justify-content: center; margin-bottom: 16px;">
        <img src="${imageUrl}" style="max-width: 95%; max-height: 85vh; object-fit: contain; border: 1px solid #ccc;" alt="${title}" />
      </div>
      <div style="font-size: 10px; color: #888; border-top: 1px dashed #ccc; padding-top: 8px;">
        Generated by Falcon POS & Workshop ERP · ${new Date().toLocaleDateString('en-GB')}
      </div>
    </div>
  `;

  triggerDirectPrint({ html, title });
}

/**
 * Subscribe to print preview events
 */
export function subscribeToPrintPreview(
  cb: (detail: PrintPreviewEventDetail | null) => void
): () => void {
  if (typeof window === 'undefined') return () => {};

  const handler = (e: Event) => {
    const custom = e as CustomEvent<PrintPreviewEventDetail>;
    cb(custom.detail || null);
  };

  window.addEventListener(PRINT_EVENT_NAME, handler);
  return () => {
    window.removeEventListener(PRINT_EVENT_NAME, handler);
  };
}
